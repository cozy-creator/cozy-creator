class Sized(msgspec.Struct, kw_only=True):
    mib: Annotated[float, Range(0.25, 256)] = 26
    seed: int = 0


class Made(msgspec.Struct):
    video: VideoFile


@app.entrypoint(accelerator=False)
def made(payload: Sized, out: Outputs) -> Made:
    pad = int(payload.mib * 2**20) - len(CLIP)
    return Made(out.save_bytes(CLIP + struct.pack(">I4s", pad, b"free") + os.urandom(pad - 8), media_type="video/mp4"))
